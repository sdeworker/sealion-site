    for slug in sorted(slugs):
        src = f"src/content/{BASE_LANG}/{div}/{slug}.html"
        if not os.path.exists(src):
            print("  跳过(无母版):", src); continue
        raw = open(src, encoding="utf-8").read()
        meta_s, _, body = raw.partition("\n---\n")
        meta = json.loads(meta_s)
        key = (div, slug)
        if key not in HERO:
            print("  跳过(无俄语文案):", key); continue
        eyebrow, h1, lead = HERO[key]

